"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { cn } from "@/lib/utils";
import type { CustomerNavItem } from "@/lib/customer-navigation";

interface CustomerNavigationProps {
  items: CustomerNavItem[];
  ariaLabel?: string;
  className?: string;
  itemClassName?: string;
  iconClassName?: string;
  activeClassName?: string;
}

export function CustomerNavigation({
  items,
  ariaLabel = "Customer navigation",
  className,
  itemClassName,
  iconClassName,
  activeClassName,
}: CustomerNavigationProps) {
  const pathname = usePathname();

  return (
    <nav aria-label={ariaLabel} className={className}>
      <ul className="space-y-1">
        {items.map((item) => {
          const isActive = item.exact
            ? pathname === item.href
            : pathname.startsWith(item.href);

          return (
            <li key={item.href}>
              <Link
                href={item.href}
                aria-current={isActive ? "page" : undefined}
                className={cn(
                  "flex items-center gap-3 rounded-md px-3 py-2 text-sm font-medium transition-colors",
                  "focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-500",
                  isActive
                    ? cn(
                        "bg-brand-50 text-brand-700 dark:bg-brand-900/40 dark:text-brand-400",
                        activeClassName,
                      )
                    : "text-neutral-600 hover:bg-neutral-100 hover:text-neutral-900 dark:text-neutral-400 dark:hover:bg-neutral-800 dark:hover:text-neutral-100",
                  itemClassName,
                )}
              >
                {item.icon && (
                  <NavIcon
                    name={item.icon}
                    className={cn("h-5 w-5 shrink-0", iconClassName)}
                    active={isActive}
                  />
                )}
                <span>{item.label}</span>
              </Link>
            </li>
          );
        })}
      </ul>
    </nav>
  );
}

